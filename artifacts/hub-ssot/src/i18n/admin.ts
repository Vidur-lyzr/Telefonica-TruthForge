import type { Lang } from "../components/app-provider";

export function localeFor(lang: Lang): string {
  switch (lang) {
    case "ES":
      return "es-ES";
    case "DE":
      return "de-DE";
    case "PT":
      return "pt-BR";
    default:
      return "en-GB";
  }
}

